/**
 * Emit the wire contract fixture.
 *
 * This runs the REAL TypeScript client domain code (goods received, shift open,
 * a manual movement, checkout, payment) and writes the resulting outbox envelopes
 * plus the seed data they reference to `contract/events.json`.
 *
 * The Kotlin server's `WireContractTest` reads that file, seeds its PostgreSQL
 * database from it, applies the events with the real `EventApplier`, and asserts
 * the outcome. That is the guard against the two languages disagreeing about the
 * payload shape: a renamed or retyped field on either side fails a test.
 *
 * Run with:  npm run contract:emit
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkout } from '../src/domain/checkout.ts';
import { disburseStock, receiveGoods } from '../src/domain/inventory.ts';
import { confirmPayment, createPayment } from '../src/domain/payments.ts';
import { openShift } from '../src/domain/shifts.ts';
import { toSyncEvent } from '../src/sync/client.ts';
import { seedStore, STORE_ID } from '../tests/helpers.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const store = seedStore({ deviceName: 'TILL-1' });
const { db, deviceId, manager, cashier, supplier, products } = store;

// 1. Stock in.
receiveGoods(db, {
  deviceId,
  supplierId: supplier.supplier_id,
  receivedBy: manager.user_id,
  reference: 'INV-1043',
  lines: [
    { productId: products['WATER-500']!.product_id, quantity: 120, unitCost: 90 },
    { productId: products['MILO-400']!.product_id, quantity: 24, unitCost: 3050 },
  ],
});

// 2. Shift open.
const shift = openShift(db, { deviceId, userId: cashier.user_id, openingFloat: 10_000 });

// 3. A manual movement, so `stock.movement` is covered too.
disburseStock(db, {
  deviceId,
  productId: products['WATER-500']!.product_id,
  quantity: 4,
  userId: manager.user_id,
  reason: 'damaged in transit',
});

// 4. Checkout with a discount, inside the open shift.
const { sale } = checkout(db, {
  deviceId,
  cashierId: cashier.user_id,
  shiftId: shift.shift_id,
  lines: [
    { productId: products['WATER-500']!.product_id, quantity: 6 },
    { productId: products['MILO-400']!.product_id, quantity: 2, discount: 200 },
  ],
});

// 5. Payment confirmed.
const payment = createPayment(db, { saleId: sale.sale_id, method: 'cash', amount: sale.total });
confirmPayment(db, payment.payment_id);

const rows = db.prepare('SELECT * FROM outbox ORDER BY seq').all() as unknown as Parameters<typeof toSyncEvent>[0][];
const events = rows.map(toSyncEvent);

const contract = {
  generatedAt: new Date().toISOString(),
  note: 'Generated by scripts/emit-contract.ts from real client domain code. Consumed by server WireContractTest.',
  seed: {
    storeId: STORE_ID,
    deviceId,
    cashierId: cashier.user_id,
    managerId: manager.user_id,
    supplierId: supplier.supplier_id,
    products: Object.values(products).map((p) => ({
      productId: p.product_id,
      sku: p.sku,
      name: p.name,
      unitPrice: p.unit_price,
      costPrice: p.cost_price,
      taxRateBp: p.tax_rate_bp,
      lowStockThreshold: p.low_stock_threshold,
    })),
  },
  // What the device expects the server to compute. The Kotlin test asserts these.
  expectations: {
    productId: products['WATER-500']!.product_id,
    stockOnHandAfter: 120 - 4 - 6,
    saleTotal: sale.total,
    saleTaxTotal: sale.tax_total,
    receiptNumber: sale.receipt_number,
  },
  events,
};

mkdirSync(resolve(root, 'contract'), { recursive: true });
const outPath = resolve(root, 'contract/events.json');
writeFileSync(outPath, `${JSON.stringify(contract, null, 2)}\n`, 'utf8');

console.log(`Wrote ${events.length} event(s) to ${outPath}`);
for (const event of events) console.log(`  seq ${event.seq}  ${event.eventType}`);
console.log(`Sale total ${sale.total}, tax ${sale.tax_total}, receipt ${sale.receipt_number}`);
